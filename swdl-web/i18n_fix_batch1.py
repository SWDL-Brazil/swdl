def set_path(obj, path, value):
    parts = path.split('.')
    cur = obj
    for i, p in enumerate(parts[:-1]):
        if p.isdigit():
            cur = cur[int(p)]
        else:
            nxt = parts[i + 1]
            if p not in cur or not isinstance(cur[p], (dict, list)):
                cur[p] = [] if nxt.isdigit() else {}
            elif isinstance(cur[p], dict) and nxt.isdigit() and not cur[p]:
                cur[p] = []
            elif isinstance(cur[p], list) and not nxt.isdigit():
                pass
            cur = cur[p]
    last = parts[-1]
    if last.isdigit():
        idx = int(last)
        if not isinstance(cur, list):
            cur = list(cur.values()) if isinstance(cur, dict) else cur
        while len(cur) <= idx:
            cur.append(None)
        cur[idx] = value
    else:
        cur[last] = value


def get_path(obj, path):
    parts = path.split('.')
    cur = obj
    for p in parts:
        if p.isdigit():
            cur = cur[int(p)]
        else:
            cur = cur.get(p)
            if cur is None:
                return None
    return cur


